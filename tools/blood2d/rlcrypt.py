# The map holds geometry, tile numbers, shades, decorations and marker sprites. It contains no game data: every
# texture is a tile number that the player's own Blood install supplies at run time.
#
# What the Crypt is: between runs the player walks around Caleb's crypt (like the House in Hades). The mod's C++
# does all the interaction: it finds the invisible marker sprites placed here and reacts to the player standing
# near them. The marker interface is fixed (roguelite.cpp depends on it):
#   type 0, statnum 0, cstat 0x8000 (invisible), with an xsprite whose data4 = 0x524C and data1 = feature id:
#     1 Armory (in front of the weapon counter), 2 Covenant (in front of the altar),
#     3 Records (in front of the tombstone), 10..15 portals 0..5 (inside each portal alcove's own sector).
#   The marker's xy is where the player stands; its z is the floor; its angle faces the feature.
# Plus a stock single-player start (type 1, xsprite data1 = 0, as on E1M1), and the map header's start
# position, angle and sector set to match it.
#
# Layout (map units; x east, y south; 16 map units = 1 world unit; the player's radius is 192):
#   grave (start room)  1792 x 1536, ceiling 112 wu, an open coffin; the start faces north to the doorway
#   doorway             640 x 384, ceiling 80 wu
#   nave                4096 wide x 5120 long, ceiling 192 wu; a raised central vault (2048 x 3584, 256 wu);
#                       4 pillars; the Records tombstone near the doorway
#   Armory bay          west side, 640 deep x 2048 long: a stone counter 20 wu high with the 8 weapons lying on it
#   Covenant bay        east side, 768 x 1536, a dais one step up, the altar, the rose window
#   chancel             4096 x 512 along the north end, one step up
#   portal alcoves      six, 512 wide x 512 deep, two steps up, each its own sector, vortex back wall
# The sizes are about 3-4x the first sketch: Blood's player is 384 units wide, so a 160-192 wide alcove could not
# be entered. Lighting is sector and wall shade only: the nave is dim, the alcoves and the altar brightest.
#
# File format: Blood v7 (version 0x0700, mattid 0x7474614d), mirroring dbLoadMap in
# source/games/blood/src/db.cpp: the header encrypted with key 0x7474614d, MAPHEADER2 with key numwalls, the sky
# offsets with key 2 << pskybits, sectors with key revision * 40, walls with (revision * 40) | 0x7474614d,
# sprites with (revision * 44) | 0x7474614d, each sprite followed by its 56-byte xsprite (not encrypted) packed
# in the BitReader's field order, then the CRC32 of everything before it. Conventions copied from the stock maps:
# outer wall loops clockwise on the 2D map (positive signed area), holes counterclockwise; extra = -1 where there
# is no x-structure; xsprite indices count down from 2047; xsprite.reference = the sprite's index;
# xrepeat = length / 128 with yrepeat 8 for square texels.
