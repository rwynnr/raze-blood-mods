def crypt(buf, key):
    """dbCrypt: XOR each byte with the key's low byte, the key counting up by one per byte (it is its own inverse)."""
    return bytes(b ^ ((key + i) & 0xFF) for i, b in enumerate(buf))


def encode_xsprite(values):
    """Packs an xsprite the way dbLoadMap's BitReader reads it: fields in order, each least significant bit first."""
    bits, pos = bytearray(XSPRITE_SIZE), 0
    unknown = set(values) - {f[0] for f in XSPRITE_FIELDS}
    assert not unknown, unknown
    for name, n, signed in XSPRITE_FIELDS:
        v = values.get(name, 0)
        lo, hi = (-(1 << (n - 1)), (1 << (n - 1)) - 1) if signed else (0, (1 << n) - 1)
        assert lo <= v <= hi, (name, v)
        v &= (1 << n) - 1
        for i in range(n):
            if (v >> i) & 1:
                bits[pos >> 3] |= 1 << (pos & 7)
            pos += 1
    return bytes(bits)


def pack_header(h):
    raw = struct.pack(HEADER_FMT, h["x"], h["y"], h["z"], h["ang"], h["sect"], h["pskybits"], h["visibility"],
                      h["mattid"], h["parallax"], h["revision"], h["numsectors"], h["numwalls"], h["numsprites"])
    enc = crypt(raw, MATTID)
    # The loader decrypts the header only when the raw mattid is none of these three; make sure it will.
    assert struct.unpack_from("<i", enc, 22)[0] not in (0, 0x7474614D, 0x4D617474)
    return enc


def pack_xheader(numwalls, name=MAP_NAME, sizes=(XSPRITE_SIZE, XWALL_SIZE, XSECTOR_SIZE)):
    assert len(name) < 64
    raw = name.ljust(64, b"\0") + struct.pack("<iii", *sizes) + bytes(52)
    return crypt(raw, numwalls)


def pack_sky(offsets):
    return crypt(struct.pack("<%dh" % len(offsets), *offsets), len(offsets) * 2)


def pack_sector(s, revision):
    raw = struct.pack(SECTOR_FMT, s["wallptr"], s["wallnum"], s["ceilingz"], s["floorz"], s["ceilingstat"],
                      s["floorstat"], s["ceilingpic"], s["ceilingheinum"], s["ceilingshade"], s["ceilingpal"],
                      s["ceilingxpan"], s["ceilingypan"], s["floorpic"], s["floorheinum"], s["floorshade"],
                      s["floorpal"], s["floorxpan"], s["floorypan"], s["visibility"], s["fogpal"], s["type"],
                      s["hitag"], s["extra"])
    return crypt(raw, revision * 40)


def pack_wall(w, revision):
    raw = struct.pack(WALL_FMT, w["x"], w["y"], w["point2"], w["nextwall"], w["nextsector"], w["cstat"],
                      w["picnum"], w["overpicnum"], w["shade"], w["pal"], w["xrepeat"], w["yrepeat"], w["xpan"],
                      w["ypan"], w["type"], w["hitag"], w["extra"])
    return crypt(raw, (revision * 40) | MATTID)


def pack_sprite(s, revision):
    raw = struct.pack(SPRITE_FMT, s["x"], s["y"], s["z"], s["cstat"], s["picnum"], s["shade"], s["pal"],
                      s["clipdist"], s["detail"], s["xrepeat"], s["yrepeat"], s["xoffset"], s["yoffset"],
                      s["sectnum"], s["statnum"], s["ang"], s["owner"], s["index"], s["yvel"], s["inittype"],
                      s["type"], s["hitag"], s["extra"])
    return crypt(raw, (revision * 44) | MATTID)


def write_map(header, sectors, walls, sprites, revision=REVISION):
    """Serializes a v7 map. Sprites with extra > 0 carry 'xsprite' (a dict of XSPRITE_FIELDS values)."""
    out = bytearray(b"BLM\x1a" + struct.pack("<h", MAP_VERSION))
    out += pack_header(header)
    out += pack_xheader(len(walls))
    out += pack_sky(list(range(1 << header["pskybits"])))
    for s in sectors:
        assert s["extra"] == -1  # no xsectors in this map
        out += pack_sector(s, revision)
    for w in walls:
        assert w["extra"] == -1  # no xwalls in this map
        out += pack_wall(w, revision)
    for s in sprites:
        out += pack_sprite(s, revision)
        if s["extra"] > 0:
            out += encode_xsprite(s["xsprite"])
    out += struct.pack("<I", zlib.crc32(bytes(out)) & 0xFFFFFFFF)
    return bytes(out)


