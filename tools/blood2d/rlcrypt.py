def build_walls(S):
    """Turns the sector loops into Build sectors and walls, linking every shared edge as a two-sided pair."""
    sectors, walls = [], []
    for si, s in enumerate(S):
        start = len(walls)
        for li, loop in enumerate(s["loops"]):
            pts = oriented(loop, li == 0)
            base = len(walls)
            for k, (x, y) in enumerate(pts):
                walls.append(dict(x=x, y=y, point2=base + (k + 1) % len(pts), nextwall=-1, nextsector=-1,
                                  sector=si, hole=li > 0))
        sectors.append(dict(wallptr=start, wallnum=len(walls) - start))
    edges = {}
    for i, w in enumerate(walls):
        q = walls[w["point2"]]
        key = (w["x"], w["y"], q["x"], q["y"])
        assert key not in edges, ("duplicate directed edge", key)
        edges[key] = i
    for i, w in enumerate(walls):
        q = walls[w["point2"]]
        j = edges.get((q["x"], q["y"], w["x"], w["y"]))
        if j is not None:
            w["nextwall"], w["nextsector"] = j, walls[j]["sector"]
    # No T-junctions: a vertex in the middle of another wall would leave an opening half linked.
    pts = {(w["x"], w["y"]) for w in walls}
    for w in walls:
        q = walls[w["point2"]]
        for (x, y) in pts:
            if (x, y) in ((w["x"], w["y"]), (q["x"], q["y"])):
                continue
            cross = (q["x"] - w["x"]) * (y - w["y"]) - (q["y"] - w["y"]) * (x - w["x"])
            dot = (x - w["x"]) * (q["x"] - w["x"]) + (y - w["y"]) * (q["y"] - w["y"])
            L2 = (q["x"] - w["x"]) ** 2 + (q["y"] - w["y"]) ** 2
            assert not (cross == 0 and 0 < dot < L2), ("T-junction", (x, y), w)
    # Looks: textures, shades, repeats, and panning that runs on along each loop.
    for si, s in enumerate(S):
        sec = sectors[si]
        sec.update(ceilingz=s["ceilz"], floorz=s["floorz"], ceilingstat=0, floorstat=0, ceilingpic=s["ceilpic"],
                   ceilingheinum=0, ceilingshade=s["ceilshade"], ceilingpal=0, ceilingxpan=0, ceilingypan=0,
                   floorpic=s["floorpic"], floorheinum=0, floorshade=s["floorshade"], floorpal=0, floorxpan=0,
                   floorypan=0, visibility=0, fogpal=0, type=0, hitag=0, extra=-1, name=s["name"])
        u = {}
        for i in range(sec["wallptr"], sec["wallptr"] + sec["wallnum"]):
            w, q = walls[i], walls[walls[i]["point2"]]
            L = math.hypot(q["x"] - w["x"], q["y"] - w["y"])
            nb = S[w["nextsector"]]["name"] if w["nextsector"] >= 0 else None
            st = s["style"](dict(x1=w["x"], y1=w["y"], x2=q["x"], y2=q["y"], L=L, nb=nb, hole=w["hole"]))
            tw, th = TILES[st["pic"]]
            xrep = st["xrep"] if st["xrep"] else max(1, min(255, round(L / (8 * st["texel"]))))
            yrep = round(th * 2048 / st["fit"]) if st["fit"] else st["yrep"]
            assert 1 <= xrep <= 255 and 1 <= yrep <= 255, (s["name"], xrep, yrep)
            if i == sec["wallptr"] or walls[i - 1]["point2"] != i:   # each loop restarts the texture run
                u = {}
            xpan = 0 if st["xrep"] else int(u.get(st["pic"], 0)) % tw
            u[st["pic"]] = u.get(st["pic"], 0) + 8 * xrep
            w.update(cstat=st["cstat"], picnum=st["pic"], overpicnum=0, shade=st["shade"], pal=0, xrepeat=xrep,
                     yrepeat=yrep, xpan=xpan, ypan=0, type=0, hitag=0, extra=-1)
    return sectors, walls


def build_sprites():
    """Sprites as dicts; sectors are filled in later from their position. Markers go first."""
    P = []

    def spr(x, y, z, pic, cstat=0, rep=(64, 64), ang=0, shade=0, type=TYPE_DECORATION, yoffset=0, xsprite=None,
            clipdist=32):
        P.append(dict(x=x, y=y, z=z, cstat=cstat, picnum=pic, shade=shade, pal=0, clipdist=clipdist, detail=0,
                      xrepeat=rep[0], yrepeat=rep[1], xoffset=0, yoffset=yoffset, statnum=0, ang=ang, owner=-1,
                      yvel=0, inittype=0, type=type, hitag=0, xsprite=xsprite))

    def marker(x, y, z, feature, ang):
        spr(x, y, z, MARKER_PIC, CS_INVISIBLE, ang=ang, xsprite=dict(data1=feature, data4=MARKER_TAG))

    # The single-player start, as the stock maps place theirs (E1M1: type 1, xsprite data1 = player 0).
    spr(0, 1088, 0, START_PIC, CS_YCENTER, ang=ANG_N, shade=-8, type=TYPE_SP_START, xsprite=dict(data1=0))
    # The feature markers: where the player stands to use each feature.
    marker(-1728, -2560, 0, FEATURE_ARMORY, ANG_W)
    marker(2208, -2560, -4 * ZU, FEATURE_COVENANT, ANG_E)
    marker(704, -640, 0, FEATURE_RECORDS, ANG_E)
    for i, x in enumerate(ALCOVE_X):
        marker(x + ALCOVE_W // 2, NORTH_Y - ALCOVE_D // 2, ALCOVE_FLOOR, FEATURE_PORTAL0 + i, ANG_N)

    # The Armory: the weapons lie flat on the counter in Blood's key order, read left to right by a player facing
    # the wall (west): back row flare gun, sawed-off, tommy gun, napalm launcher; front row TNT, tesla cannon,
    # life leech, voodoo doll. Floor-aligned on purpose: Raze draws these pickup tiles as spinning voxels when
    # they are face- or wall-aligned (r_voxels), but never a floor sprite. Each image's top points at the wall.
    rep, unit = 24, 24 / 4      # 24 = half the pickup size; map units per pixel at that repeat
    y_south, y_north = -1536, -3584
    for row_x, names in ((-2512, ["flare gun", "sawed-off", "tommy gun", "napalm launcher"]),
                         (-2224, ["TNT", "tesla cannon", "life leech", "voodoo doll"])):
        lengths = [(WEAPONS[n][2] if n == "life leech" else WEAPONS[n][1]) * unit for n in names]
        gap = ((y_south - y_north) - sum(lengths)) / (len(names) + 1)
        y = y_south
        for n, L in zip(names, lengths):
            tile, w, h, yoff = WEAPONS[n]
            y -= gap
            # The life leech is a staff, drawn upright: lay its length along the counter, skull to the north.
            spr(row_x, round(y - L / 2), COUNTER_TOP - 128, tile, CS_FLOOR, (rep, rep),
                ANG_N if n == "life leech" else ANG_W, shade=-8, yoffset=-yoff)
            y -= L
    # Armory dressing: two banners and a medallion on the back wall, torches on the side walls, candles.
    spr(-2684, -1984, -90 * ZU, BANNER_LION, CS_WALL | CS_ONESIDE | CS_YCENTER, (24, 24), ANG_E)
    spr(-2684, -3136, -90 * ZU, BANNER_GRIFFIN, CS_WALL | CS_ONESIDE | CS_YCENTER, (24, 24), ANG_E)
    spr(-2684, -2560, -90 * ZU, MEDALLIONS[0], CS_WALL | CS_ONESIDE | CS_YCENTER, (24, 24), ANG_E)
    for y in (-1568, -3552):
        spr(-2368, y, -60 * ZU, TORCH_SCONCE, CS_YCENTER | CS_HITSCAN, ang=0, shade=-8, type=TYPE_TORCH)
    for y in (-1600, -3520):
        spr(-2112, y, COUNTER_TOP, CANDLE, CS_YCENTER | CS_HITSCAN, (40, 48), shade=-8, type=TYPE_CANDLE)

    # The Covenant: the rose window over the altar, skull candelabras, candles and a chalice on the altar,
    # a red sigil where the player stands, skulls in the corners.
    spr(2812, -2560, -104 * ZU, ROSE_WINDOW, CS_WALL | CS_ONESIDE | CS_YCENTER, (24, 24), ANG_W)
    for y in (-2944, -2176):
        spr(2560, y, -4 * ZU, SKULL_CANDELABRA, CS_BLOCK | CS_YCENTER | CS_HITSCAN, (56, 56), shade=-8,
            type=TYPE_TORCH)
    for y in (-2720, -2400):
        spr(2608, y, ALTAR_TOP, CANDLE, CS_YCENTER | CS_HITSCAN, (32, 40), shade=-8, type=TYPE_CANDLE)
    spr(2576, -2560, ALTAR_TOP, CHALICE, 0, (20, 20), ANG_W)
    spr(2208, -2560, -4 * ZU - 128, SIGIL_RED, CS_FLOOR, (32, 32), ANG_N, shade=-16)
    for y in (-3232, -1888):
        spr(2720, y, -4 * ZU, SKULL_PILE, CS_YCENTER, (40, 40))

    # The portal alcoves: candles in the back corners, a blue sigil on the floor, and over each mouth one of the
    # six key medallions (skull, eye, fire, dagger, spider, moon) to tell them apart.
    for i, x in enumerate(ALCOVE_X):
        for cx in (x + 72, x + ALCOVE_W - 72):
            spr(cx, NORTH_Y - ALCOVE_D + 72, ALCOVE_FLOOR, CANDLE, CS_YCENTER | CS_HITSCAN, (40, 48), shade=-8,
                type=TYPE_CANDLE)
        spr(x + ALCOVE_W // 2, NORTH_Y - ALCOVE_D // 2, ALCOVE_FLOOR - 128, SIGIL_BLUE, CS_FLOOR, (24, 24), ANG_N,
            shade=-16)
        spr(x + ALCOVE_W // 2, NORTH_Y + 4, ALCOVE_CEIL - 18 * ZU, MEDALLIONS[i], CS_WALL | CS_ONESIDE | CS_YCENTER,
            (24, 24), ANG_S)

    # The chancel: tall candlesticks at its ends, a skull candle at the foot of each pier between the alcoves.
    for x in (-1952, 1952):
        spr(x, -5376, -2 * ZU, CANDLESTICK, CS_BLOCK | CS_YCENTER | CS_HITSCAN, shade=-8, type=TYPE_TORCH)
    for x in (-1280, -640, 0, 640, 1280):
        spr(x, NORTH_Y + 64, -2 * ZU, SKULL_CANDLE, CS_YCENTER, (24, 24), shade=-128)

    # The nave: torches and banners on the long walls, skull candles by the pillars, a medallion over the door,
    # and the Records tombstone facing the path out of the doorway, with candles and skulls.
    for x, banner_a, banner_b, ang in ((-2016, BANNER_GOLD, BANNER_TEAL, ANG_E), (2016, BANNER_TEAL, BANNER_GOLD, ANG_W)):
        for y, banner in ((-896, banner_a), (-4224, banner_b)):
            spr(x, y, -60 * ZU, TORCH_SCONCE, CS_YCENTER | CS_HITSCAN, shade=-8, type=TYPE_TORCH)
            spr(x - 28 if x < 0 else x + 28, y, -140 * ZU, banner, CS_WALL | CS_ONESIDE | CS_YCENTER, (32, 32), ang)
    for cx in (-1376, 1376):
        for cy in (-1024, -4096):
            spr(cx, cy, 0, SKULL_CANDLE, CS_YCENTER, (24, 24), shade=-128)
    spr(0, -4, -96 * ZU, MEDALLIONS[0], CS_WALL | CS_ONESIDE | CS_YCENTER, (32, 32), ANG_N)
    # Its picanm y offset (43) is a pixel short of half its height (88), so it would sink 1/64 of its repeat
    # into the floor; stock maps lift it the same way (z = floor - 256 at repeat 64).
    spr(1152, -640, -160, TOMBSTONE, CS_BLOCK | CS_YCENTER | CS_HITSCAN, (40, 40), ANG_W)
    for y in (-832, -448):
        spr(1024, y, 0, CANDLE, CS_YCENTER | CS_HITSCAN, (40, 48), shade=-8, type=TYPE_CANDLE)
    spr(1376, -416, 0, SKULL_PILE, CS_YCENTER, (40, 40))

    # The grave: candles round the coffin, a candelabra at its head, torches by the doorway, a medallion over the
    # coffin, skulls in the corners.
    for x, y in ((-640, 1344), (-640, 1728), (640, 1440), (640, 1632)):
        spr(x, y, 0, CANDLE, CS_YCENTER | CS_HITSCAN, (40, 48), shade=-8, type=TYPE_CANDLE)
    spr(-704, 1536, 0, CANDELABRA, CS_BLOCK | CS_YCENTER, (48, 48), shade=-128)
    for x in (-608, 608):   # lower than the nave's: the flame effect reaches ~40 wu above the mount
        spr(x, 416, -52 * ZU, TORCH_SCONCE, CS_YCENTER | CS_HITSCAN, shade=-8, type=TYPE_TORCH)
    spr(0, 1916, -52 * ZU, MEDALLIONS[0], CS_WALL | CS_ONESIDE | CS_YCENTER, (32, 32), ANG_N)
    spr(-768, 1792, 0, SKULL_PILE, CS_YCENTER, (40, 40))
    spr(768, 1808, 0, SKULL, CS_YCENTER, (40, 40))
    return P


def build():
    S = build_sectors()
    sectors, walls = build_walls(S)
    sprites = build_sprites()
    names = [s["name"] for s in sectors]
    # Each sprite's sector is the one whose walls contain it (exactly one, since sectors do not overlap).
    xs_index = 2047
    for i, s in enumerate(sprites):
        hits = [k for k, sec in enumerate(sectors) if inside(walls, sec, s["x"], s["y"])]
        assert len(hits) == 1, ("sprite outside the map or on an edge", i, s, hits)
        s["sectnum"], s["index"] = hits[0], i
        if s["xsprite"] is not None:
            s["xsprite"] = dict(s["xsprite"], reference=i)
            s["extra"], xs_index = xs_index, xs_index - 1
        else:
            s["extra"] = -1
    start = sprites[0]
    assert start["type"] == TYPE_SP_START
    header = dict(x=start["x"], y=start["y"], z=start["z"], ang=start["ang"], sect=start["sectnum"],
                  pskybits=SKY_BITS, visibility=VISIBILITY, mattid=MATTID, parallax=0, revision=REVISION,
                  numsectors=len(sectors), numwalls=len(walls), numsprites=len(sprites))
    # The interface the C++ relies on.
    feats = {s["xsprite"]["data1"]: s for s in sprites if s["xsprite"] and s["xsprite"].get("data4") == MARKER_TAG}
    assert sorted(feats) == [1, 2, 3, 10, 11, 12, 13, 14, 15], sorted(feats)
    for f, s in feats.items():
        assert s["type"] == 0 and s["statnum"] == 0 and s["cstat"] & CS_INVISIBLE
        assert s["z"] == sectors[s["sectnum"]]["floorz"]
        if f >= FEATURE_PORTAL0:
            assert names[s["sectnum"]] == "alcove %d" % (f - FEATURE_PORTAL0)
    assert names[feats[FEATURE_COVENANT]["sectnum"]] == "covenant"
    assert names[start["sectnum"]] == "grave"
    assert len(sectors) < 40 and len(walls) < 400 and len(sprites) < 150, (len(sectors), len(walls), len(sprites))
    return header, sectors, walls, sprites


def main(argv):
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out = argv[1] if len(argv) > 1 else os.path.join(root, "wadsrc", "static", "filter", "blood", "rlcrypt.map")
    header, sectors, walls, sprites = build()
    data = write_map(header, sectors, walls, sprites)
    with open(out, "wb") as f:
        f.write(data)
    print("%s: %d bytes, %d sectors, %d walls, %d sprites" % (out, len(data), len(sectors), len(walls), len(sprites)))


if __name__ == "__main__":
    main(sys.argv)
