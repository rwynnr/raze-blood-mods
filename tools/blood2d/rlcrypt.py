def rect(x0, y0, x1, y1):
    """Rectangle as a clockwise loop (north edge west to east first)."""
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


def signed_area(loop):
    return sum(loop[i][0] * loop[(i + 1) % len(loop)][1] - loop[(i + 1) % len(loop)][0] * loop[i][1]
               for i in range(len(loop))) / 2


def oriented(loop, outer):
    """Outer loops get a positive signed area (clockwise on Build's y-down map), holes a negative one."""
    a = signed_area(loop)
    assert a != 0
    return list(loop) if (a > 0) == outer else list(reversed(loop))


def inset(loop, d):
    """The loop (positive area) offset inward by d, vertices rounded to integers."""
    n, lines, out = len(loop), [], []
    for i in range(n):
        (x1, y1), (x2, y2) = loop[i], loop[(i + 1) % n]
        dx, dy = x2 - x1, y2 - y1
        L = math.hypot(dx, dy)
        nx, ny = -dy / L * d, dx / L * d   # the interior is on the left of each edge
        lines.append(((x1 + nx, y1 + ny), (dx, dy)))
    for i in range(n):
        (px, py), (ux, uy) = lines[i - 1]
        (qx, qy), (vx, vy) = lines[i]
        den = ux * vy - uy * vx
        t = ((qx - px) * vy - (qy - py) * vx) / den
        out.append((round(px + ux * t), round(py + uy * t)))
    return out


def inside(walls, sec, x, y):
    """Build's inside(): crossing parity over all of a sector's walls, so holes count as outside."""
    c = 0
    for i in range(sec["wallptr"], sec["wallptr"] + sec["wallnum"]):
        w1, w2 = walls[i], walls[walls[i]["point2"]]
        y1, y2 = w1["y"] - y, w2["y"] - y
        if (y1 ^ y2) < 0:
            x1, x2 = w1["x"] - x, w2["x"] - x
            c ^= x1 if (x1 ^ x2) >= 0 else (x1 * y2 - x2 * y1) ^ y2
    return c < 0


